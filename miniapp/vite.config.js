import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react()],
  build: {
    // Минификатор по умолчанию переписывает `min-width: 720px` в
    // `@media (width>=720px)` - синтаксис диапазонов из Media Queries 4.
    // Браузеры до Chrome 104 / Safari 16.4 такой блок ПРОПУСКАЮТ ЦЕЛИКОМ, а
    // во встроенном Chromium десктопного клиента ВК версия своя и обычно
    // отстаёт. Так молча отвалились и фон на широком экране, и ограничение
    // колонки. Цель сборки задана консервативно, чтобы медиазапросы
    // оставались в классическом виде.
    cssTarget: ['chrome87', 'safari13.1', 'firefox78', 'edge88'],
    // Иконки предметов весят 1-3 КБ каждая, то есть по умолчанию Vite
    // зашил бы все 79 в JS как base64: бандл распух с 405 до 624 КБ,
    // base64 добавил к весу ещё треть, а loading="lazy" на data-URL не
    // действует вовсе - всё грузилось бы разом при открытии. Ноль
    // заставляет вынести их отдельными файлами: браузер тянет только
    // видимые и кэширует каждую отдельно. Порог не ноль, а 512 байт:
    // иконки навигации по ~280 байт выгоднее оставить внутри, чем
    // тянуть восемью отдельными запросами.
    assetsInlineLimit: 512,
  },
  server: {
    // Локально проксируем запросы к тому же aiohttp-серверу, что и бот
    // (main.py, порт из PORT/.env) — без этого понадобился бы CORS и для dev.
    proxy: {
      '/api/miniapp': {
        target: 'http://localhost:8080',
        changeOrigin: true,
      },
    },
  },
})
