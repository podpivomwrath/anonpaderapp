/** Шаги гайда: с главы текущего раздела, дальше по порядку и по кругу.
 *  Глава шапки идёт первой, если гайд запущен с «Персонажа». */
export function guideSteps(startTab, visibleTabs) {
  const chapters = GUIDE_CHAPTERS.filter((c) => visibleTabs.includes(c.tab));
  let start = chapters.findIndex((c) => c.tab === startTab);
  if (start < 0) start = 0;
  const ordered = [...chapters.slice(start), ...chapters.slice(0, start)];
  return ordered.flatMap((chapter, ci) => chapter.steps.map((step, si) => ({
    ...step,
    tab: chapter.tab,
    chapter: chapter.title,
    chapterIndex: ci,
    chapterStep: si,
    chapterSize: chapter.steps.length,
  })));
}
