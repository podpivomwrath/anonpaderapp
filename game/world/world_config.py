# Кольца: (dist_min, dist_max, (level_min, level_max)) по расстоянию до
# Монолита (grid.monolith_distance). Покрывает 0..WORLD_RADIUS без пропусков.
# Пропорции колец - те же, что на картинке карты (tools/map_art_prompt.md).
# ЕДИНСТВЕННЫЙ источник границ колец: тиры озёр и рудников, броски трофеев и
# кольца мировых боссов берут их отсюда (ring_bounds ниже).
ZONE_TABLE = [
    (24, 30, (1, 15)),
    (15, 23, (16, 30)),
    (7, 14, (31, 45)),
    (2, 6, (46, 60)),
    (0, 1, (60, 60)),    # центр, эндгейм — потолок уровня (патч 34, ч.0: MAX_LEVEL=60)
]


def ring_bounds(tier: int) -> tuple[int, int]:
    """(dist_min, dist_max) кольца: 1 - внешнее, 5 - центр."""
    lo, hi, _levels = ZONE_TABLE[tier - 1]
    return lo, hi


def ring_tier_for_dist(dist: int) -> int:
    """За краем мира (dist > WORLD_RADIUS) - внешнее кольцо, а не центр:
    клетка, куда игрок попасть не должен, не может давать эндгейм."""
    for tier, (lo, hi, _levels) in enumerate(ZONE_TABLE, start=1):
        if lo <= dist <= hi:
            return tier
    return 1

