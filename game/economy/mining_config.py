#
# Бросок: u = U ** k. Чем меньше k, тем лучше градации.
#     k = MINE_GRADE_K[тир] * уровневый множитель (см. GRADE_K_* ниже)

#: (нижняя граница броска, id, название). Мелочи нет: мелкой руды не бывает,
