"""Числа горного дела (патч 59): время добычи, градации, спавн руды, уровень.

Каталог (названия/лор/координаты рудников) — content/mining/ores.json и
content/mining/mines.json. Здесь только калибруемые числа, как у рыбалки.

Чем горное дело принципиально отличается от рыбалки:

1. Руду НЕЛЬЗЯ продать ни одному НПС. Она нужна будет для прокачки снаряжения
   и инструментов (сама прокачка — отдельный патч), а между игроками торговля
   появится позже. Значит у горного дела нет выхода в золото вообще, и
   балансировать его против фарма мобов не нужно и нечем.

2. Руда в СТАТИЧНЫХ рудниках — общий ресурс сервера, а не бесконечный кран.
   Она спавнится от активности игроков (см. ORE_SPAWN_CHANCE_PER_EXPLORATION)
   и ограничена потолком на жилу. Поэтому рудник может оказаться пустым, а
   полный рудник на глубоком кольце — местом встречи, где открыто PvP.

3. Ограничитель добычи — ВРЕМЯ и только оно: добыча полностью блокирует
   действия игрока, носить можно сколько угодно, провалов нет. Единственное,
   что может случиться за эти минуты, — на тебя нападёт другой игрок.
"""

