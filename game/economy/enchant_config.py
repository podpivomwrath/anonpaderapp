"""Заточка кованых уникалок (2026-11-13, решения владельца) - числа.

Затачивается только кованая вещь (craft_spec): уникалка с босса, которую
игрок уже выковал у кузнеца. Ступени +1..+10, каждая +2% к характеристикам
вещи, в PvP тоже полностью (владелец передумал резать).

Попытка: либо +1, либо откат на ступень. Шанс отката - от градации руды,
которую игрок кладёт в попытку. Цена попытки - звёздная пыль (от 3, растёт
со ступенью) и руда высоких тиров: на +1..+5 Багряный сросток, с +6 Живой
камень. Пыль не меняли: игроки перестали её копить, когда она была не
нужна (владелец).

Логика - services/craft_service.enchant, характеристики -
game/economy/crafting.crafted_stats.
"""

MAX_LEVEL = 10
#: Прибавка к характеристикам вещи за ступень (доля).
STAT_PER_LEVEL = 0.02

#: Руда попытки по целевой ступени: до HIGH_FROM - LOW_ORE, дальше HIGH_ORE.
LOW_ORE = "crimson_cluster"
HIGH_ORE = "living_stone"
HIGH_FROM = 6

#: Шанс отката на ступень по градации руды попытки.
ROLLBACK: dict[str, float] = {
    "common": 0.50,
    "rare": 0.35,
    "epic": 0.20,
    "legendary": 0.10,
}


def dust_cost(target: int) -> int:
    """Пыли за попытку на ступень target: +1 - 3, дальше на 1 больше."""
    return 3 + (target - 1)


def ore_cost(target: int) -> tuple[str, int]:
    """(руда, сколько штук) за попытку на ступень target."""
    if target < HIGH_FROM:
        return LOW_ORE, target
    return HIGH_ORE, target - HIGH_FROM + 1


def multiplier(level: int) -> float:
    """Во сколько раз характеристики вещи больше незаточенных."""
    return 1.0 + STAT_PER_LEVEL * max(level, 0)
