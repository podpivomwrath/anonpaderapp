from dataclasses import dataclass, field

COMMON, RARE, EPIC, MYTHIC = "common", "rare", "epic", "mythic"
#: Кривая мастерства по редкости (runes_config.CURVES).
CURVE_BY_RARITY = {COMMON: "normal", RARE: "normal", EPIC: "tight", MYTHIC: "very_tight"}

#: Ступень I - на пути к 110%: доля от копий до 110% (25 из 81 у обычной кривой).
STEP_ONE_SHARE = 25 / 81

#: Метки навыка для огранок (runes_config.SKILL_TAG_TITLES). damage и long_cd
#: дополнительно ставятся сами: урон > 0, перезарядка от 4 ходов.
DAMAGE, CONTROL, DOT, DURATION, LONG_CD, HEAL = "damage", "control", "dot", "duration", "long_cd", "heal_shield"


@dataclass(frozen=True)
class Step:
    text: str
    mods: dict = field(default_factory=dict)


@dataclass(frozen=True)
class AbilityDef:
    id: str
    rarity: str
    tags: tuple[str, ...]
    #: I, II, (III а, III б), IV.
    one: Step
    two: Step
    fork: tuple[Step, Step]
    four: Step
    #: Действует всегда, пока руна вставлена (база навыка вне контента).
    base: dict = field(default_factory=dict)
    #: Короткое описание для карточки руны: что делает навык.
    summary: str = ""

    @property
    def curve(self) -> str:
        return CURVE_BY_RARITY[self.rarity]


def _k(kind: str, skill_id: str) -> str:
    return f"{kind}:{skill_id}"


def A(sid, rarity, tags, summary, one, two, fork_a, fork_b, four, base=None) -> AbilityDef:  # noqa: N802
    """Короткая запись: ступени - (текст, {ключ: значение}); в ключах "@"
    заменяется на ":<id навыка>" - skill_bonus@ -> skill_bonus:warrior_cleave."""
    def step(pair):
        text, mods = pair
        return Step(text, {(k[:-1] + ":" + sid if k.endswith("@") else k): v for k, v in mods.items()})
    return AbilityDef(sid, rarity, tuple(tags), step(one), step(two), (step(fork_a), step(fork_b)), step(four),
                      base or {}, summary)


