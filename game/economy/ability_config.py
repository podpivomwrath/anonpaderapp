def mods_for(skill_id: str, step: int, fork: int = 0) -> dict[str, float]:
    """Модификаторы ступеней 1..step (fork: 1 - а, 2 - б, 0 - не выбрана)."""
    ability = BY_ID.get(skill_id)
    if ability is None:
        return {}
    picked = []
    if step >= 1:
        picked.append(ability.one)
    if step >= 2:
        picked.append(ability.two)
    if step >= 3 and fork in (1, 2):
        picked.append(ability.fork[fork - 1])
    if step >= 4:
        picked.append(ability.four)
    out: dict[str, float] = dict(ability.base)
    for s in picked:
        for key, value in s.mods.items():
            out[key] = out.get(key, 0.0) + value
    return out


def step_thresholds(curve: str) -> tuple[int, int, int, int]:
    """Сколько копий нужно для ступеней I-IV на этой кривой."""
    from game.economy import runes

    first = runes.threshold(curve, 1)
    return (round(first * STEP_ONE_SHARE), first, runes.threshold(curve, 2), runes.threshold(curve, 3))


def step_of(skill_id: str, absorbed: int) -> int:
    """Ступень руны-навыка при этом мастерстве: 0..4."""
    ability = BY_ID.get(skill_id)
    if ability is None:
        return 0
    return sum(1 for t in step_thresholds(ability.curve) if absorbed >= t)
