"""Пепельный ларец (патч 24): модификатор шанса редких градаций от длины
стрика ежедневок + флейвор-тексты редких находок. Сами градации/содержимое —
в content/lootbox/ashen_chest.json.

ЖЁСТКОЕ ПРАВИЛО (патч 24, п.1): ларец не продаётся ни за золото, ни за
самоцветы, ни за реальные деньги — только награда за стрик. Не добавлять
в магазин/донат-офферы/биржу ни в каком виде.

Калибровка донат-эмиссии (патч 24, п.5, для будущих цен в донат-магазине и
на бирже): матожидание ≈3.7 самоцвета/ларец. Идеальный игрок за год получает
≈1350 (ларцы, 365×3.7) + ≈1300 (награды за вход) + 1775 (рубежи стрика
ежедневок) ≈ 4400 самоцветов без единого рубля — ориентир, чтобы бесплатный
игрок мог за год реально что-то себе позволить, но не всё сразу.
"""

STREAK_CHANCE_BOOST_ENABLED = True
BOOSTED_GRADES = {"crimson", "searing", "tear"}  # 🟣/🟠/🟡

# (порог стрика ежедневок, множитель шанса боевых градаций) — по возрастанию,
# действует последний порог, для которого daily_streak >= threshold.
STREAK_CHANCE_BOOST_TIERS = [
    (1, 1.0),
    (7, 1.3),
    (28, 1.6),
    (112, 2.0),
]


def boost_multiplier(daily_streak: int) -> float:
    mult = 1.0
    for threshold, m in STREAK_CHANCE_BOOST_TIERS:
        if daily_streak >= threshold:
            mult = m
    return mult


