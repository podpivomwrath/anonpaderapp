"""Крафт специализированного оружия из боссовых предметов (патч 72) —
калибруемые числа. Контент (что во что кроится и как называется) —
content/crafting/recipes.json.

Вся система стоит на двух осях руды, и у них РАЗНЫЙ смысл: тир решает,
сколько очков statов получит предмет, градация — насколько кучно эти очки
лягут в профильные статы специализации. Поэтому копить имеет смысл обе, а не
одну «самую лучшую» руду.
"""

# --- Специализации -------------------------------------------------------------

SPEC_TANK = "tank"
SPEC_DPS = "dps"
SPEC_SUPPORT = "support"
SPECS: tuple[str, ...] = (SPEC_TANK, SPEC_DPS, SPEC_SUPPORT)

SPEC_TITLES = {
    SPEC_TANK: "Танк",
    SPEC_DPS: "Урон",
    SPEC_SUPPORT: "Поддержка",
}

#: Веса розыгрыша статов. "primary" резолвится в str/agi/int по классу
#: владельца — ровно как в item_config.SLOT_STAT_SPLITS.
#:
#: Это НЕ гарантия раскладки, а предрасположенность: очки раздаются порциями,
#: каждая летит в стат, выбранный по этим весам. Сумма весов не обязана быть
#: единицей — розыгрыш нормирует сам.
SPEC_WEIGHTS: dict[str, dict[str, float]] = {
    SPEC_TANK:    {"vit": 0.45, "wil": 0.30, "primary": 0.15, "agi": 0.10},
    SPEC_DPS:     {"primary": 0.50, "agi": 0.30, "vit": 0.10, "wil": 0.10},
    SPEC_SUPPORT: {"wil": 0.45, "int": 0.30, "vit": 0.20, "agi": 0.05},
}

#: Веса для предметов, выпавших с босса. Специализации у них нет, но и ровной
#: раскладки быть не должно: суть боссовой вещи — сырьё для крафта, однако
#: носить её можно, поэтому перекос в основной стат класса сохраняется.
BOSS_ITEM_WEIGHTS: dict[str, float] = {
    "primary": 0.40, "vit": 0.20, "agi": 0.15, "wil": 0.15, "int": 0.10,
}


# --- Розыгрыш статов -----------------------------------------------------------

#: На сколько порций делится бюджет очков. Разброс предметов берётся ИМЕННО
#: отсюда, а не из множителя эффективности: раздавали бы по одному очку — и
#: закон больших чисел сделал бы все предметы одной специализации
#: неотличимыми. Меньше бросков — больше дисперсии.
ROLL_CHUNKS = 6

#: Градация руды заостряет веса: w ** k. Обычная оставляет их как есть,
#: легендарная почти гарантирует попадание в профильные статы. Тот же приём,
#: что fishing.weight_k и mining.grade_k — узнаваемо для остального кода.
GRADE_FOCUS: dict[str, float] = {
    "common": 1.0,
    "rare": 1.4,
    "epic": 1.9,
    "legendary": 2.5,
}
GRADE_FOCUS_DEFAULT = 1.0


# --- Бюджет очков --------------------------------------------------------------

#: Во сколько раз бюджет крафта больше power предмета-источника. Подобрано
#: так, чтобы САМЫЙ ПЛОХОЙ крафт (80%) был примерно равен источнику: ковать
#: не должно быть хуже, чем оставить боссовую вещь как есть.
CRAFT_POWER_MULT = 1.3


# --- Эффективность -------------------------------------------------------------

EFFICIENCY_MIN = 80
EFFICIENCY_CRAFT_MAX = 100   # выше 100 крафтом не поднять — только инструментами
EFFICIENCY_MAX = 120
EFFICIENCY_STEP = 10

#: Стартовая эффективность по тиру руды: 80 + 10*(тир-1), потолок 100.
#: Руда тира 4+ в крафт не идёт вовсе — упёрлась бы в тот же потолок; её
#: место в инструментах, где она открывает 110 и 120.
def craft_efficiency_for(ore_tier: int) -> int:
    raw = EFFICIENCY_MIN + EFFICIENCY_STEP * (ore_tier - 1)
    return min(raw, EFFICIENCY_CRAFT_MAX)


#: Максимальный тир руды, который вообще принимают в крафт оружия.
CRAFT_MAX_ORE_TIER = 3

#: Потолок, до которого качает инструмент из руды этого тира. Инструмент с
#: высоким потолком можно применить и на нижней ступени — просто расточительно,
#: и это осознанно: запрещать игроку тратить дорогое на дешёвое незачем.
TOOL_CEILING_BY_ORE_TIER: dict[int, int] = {
    1: 90,
    2: 100,
    3: 110,
    4: 120,
    5: 120,
}

#: Живой камень (тир 6) в инструменты не идёт: он остаётся под пробуждение.
TOOL_MAX_ORE_TIER = 5


# --- Цена ----------------------------------------------------------------------

#: Руды на первый крафт из боссового предмета.
CRAFT_ORE_COST = 5

#: Руды на инструмент, ПО ЦЕЛЕВОЙ ступени. Дорожает к верху лестницы:
#: кап системы — это 120%, и без подорожания игрок добирался бы туда за
#: пару вечеров, после чего у предмета не оставалось бы цели.
#:
#: Второй ограничитель — тир руды (TOOL_CEILING_BY_ORE_TIER): верхние
#: ступени требуют руды, которая сама по себе открывается уровнем горного
#: дела. Два рычага бьют в одно, поэтому каждый из них можно держать мягким.
TOOL_ORE_COST_BY_TARGET: dict[int, int] = {
    90: 3,
    100: 5,
    110: 8,
    120: 13,
}


def tool_ore_cost(target_efficiency: int) -> int:
    """Сколько руды стоит инструмент, закрывающий эту ступень."""
    return TOOL_ORE_COST_BY_TARGET[target_efficiency]

#: Каждый следующий перекрафт ЭТОГО ЖЕ предмета вдвое дороже предыдущего.
#: Без подорожания игрок за вечер добивает идеальный ролл и упирается в
#: потолок системы; с ним на один источник приходится 3-4 осмысленные
#: попытки, а дальше дешевле дождаться нового предмета с босса — то есть
#: переролл привязан к рейдам, а не к фарму руды.
#:
#: Счётчик ОДИН на смену специализации и на переролл той же: иначе игроки
#: чередовали бы роли, чтобы обойти подорожание.
RECRAFT_COST_MULT = 2.0


def recraft_ore_cost(recrafts_done: int) -> int:
    """Сколько руды стоит следующий перекрафт предмета."""
    return round(CRAFT_ORE_COST * RECRAFT_COST_MULT ** (recrafts_done + 1))
