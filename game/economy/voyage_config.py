def fmt(part_id: str, value) -> str:
    """Значение части в тексте: «10 ч в пути», «+10% к награде», «×1.3 ...»."""
    return PARTS_BY_ID[part_id].unit.format(value)


def money(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def part_name(region: str, part_id: str) -> tuple[str, str]:
    """(эмодзи, название) части снаряжения в этом городе."""
    return VOYAGES[region].parts[part_id]
