def rune_mutter(code: str) -> str:
    return f"🪨 Руна бормочет: {code}"


DIRECTIONS = {
    (0, 0): "на вашей клетке",
    (0, 1): "к северу", (0, -1): "к югу", (1, 0): "к востоку", (-1, 0): "к западу",
    (1, 1): "к северо-востоку", (-1, 1): "к северо-западу",
    (1, -1): "к юго-востоку", (-1, -1): "к юго-западу",
}


def direction(dx: int, dy: int) -> str:
    """Сторона света по смещению (север - y больше)."""
    return DIRECTIONS[((dx > 0) - (dx < 0), (dy > 0) - (dy < 0))]


def raven_line(name: str, title: str, level: int, dx: int, dy: int) -> str:
    return f"{name} ({title}, {level} ур.) - {direction(dx, dy)}"


def raven_message(lines: list[str]) -> str:
    if len(lines) == 1:
        return f"🐦‍⬛ Ворон: рядом {lines[0]}."
    return "🐦‍⬛ Ворон: рядом игроки.\n" + "\n".join(f"· {line}" for line in lines)


def hound_line(name: str, dx: int, dy: int) -> str:
    cells = max(abs(dx), abs(dy))
    if cells == 0:
        return f"🐺 Гончая скалится: {name} с клеймом здесь, на вашей клетке."
    return f"🐺 Гончая чует клеймо: {name}, {plural.count(cells, 'клетка', 'клетки', 'клеток')} {direction(dx, dy)}."


