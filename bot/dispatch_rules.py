"""Общие правила диспетчеризации сообщений (патч 40/42).

TEXT_ONLY — состояния ожидания текстового ввода (координаты маунта, выбор
стороны в PvP по цифре и т.п.) обязаны реагировать ТОЛЬКО на настоящий
текст, набранный игроком, а не на любое сообщение с таким же текстом.
Нажатие кнопки — тоже сообщение, и если его подпись случайно совпадает с
ожидаемым текстовым вводом (например кнопка «1» из другого экрана), правило
без этого фильтра перехватывает нажатие и глушит его настоящий payload-
обработчик — сам факт, что где-то в игре есть кнопка с такой же подписью,
не должен ломать текстовый ввод в другом месте, и наоборот.

Порядок обработки сообщения: payload кнопки → команды (/квест, /застрял) →
текстовый ввод в контексте текущего экрана. Любое взаимодействие через
кнопку — только payload; текстовый разбор допустим лишь там, где игрок
реально печатает свободный текст (никнейм, координаты, баг-репорт, поиск в
админке), и всегда с проверкой текущего состояния/экрана."""

from vkbottle.dispatch.rules.base import FuncRule

TEXT_ONLY = FuncRule(lambda m: m.payload is None)
